// Samples the world's land masses (Natural Earth 1:110m, via world-atlas) on an even spherical
// lattice and writes the points as quantised latitude/longitude pairs for the globe in the film.
import { readFileSync, writeFileSync } from "node:fs";
import { feature } from "topojson-client";
import { geoContains } from "d3-geo";

const topo = JSON.parse(readFileSync("node_modules/world-atlas/land-110m.json", "utf8"));
const land = feature(topo, topo.objects.land);
const N = 52000, pts = [], golden = Math.PI * (3 - Math.sqrt(5));
for (let i = 0; i < N; i++) {
  const y = 1 - (i / (N - 1)) * 2, r = Math.sqrt(1 - y * y), th = golden * i;
  const lat = Math.asin(y) * 180 / Math.PI, lon = ((Math.atan2(Math.sin(th) * r, Math.cos(th) * r) * 180 / Math.PI) + 540) % 360 - 180;
  if (lat < -60) continue; // leave Antarctica out: it reads as noise at the bottom of the globe
  if (geoContains(land, [lon, lat])) pts.push(Math.round(lat / 90 * 32767), Math.round(lon / 180 * 32767));
}
const buf = Buffer.from(new Int16Array(pts).buffer);
writeFileSync("src/film/land.js", `// Generated by scripts/build-land.mjs. ${pts.length / 2} land points as int16 lat/lon pairs.\nexport const LAND = "${buf.toString("base64")}";\n`);
console.log(pts.length / 2, "points,", buf.length, "bytes");
